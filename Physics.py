# 1. Kinetic Energy
mass = 10
velocity = 5
kinetic_energy = 0.5 * mass * velocity ** 2
print("Kinetic Energy =", kinetic_energy, "J")


# 2. Force
mass = 10
acceleration = 4
force = mass * acceleration
print("Force =", force, "N")


# 3. Acceleration
final_velocity = 20
initial_velocity = 5
time = 3
acceleration = (final_velocity - initial_velocity) / time
print("Acceleration =", acceleration, "m/s²")


# 4. Time
distance = 100
speed = 20
time = distance / speed
print("Time =", time, "seconds")


# 5. Speed
distance = 150
time = 30
speed = distance / time
print("Speed =", speed, "m/s")
